export type PhotoShape = { m: Muscle; pts: number[] };

/** Contorno suave (curvas por los puntos medios) a partir de los puntos [x1, y1, x2, y2…]. */
export function photoPath(pts: number[]): string {
  const p: [number, number][] = [];
  for (let i = 0; i < pts.length; i += 2) p.push([pts[i], pts[i + 1]]);
  const mid = (a: [number, number], b: [number, number]) => `${((a[0] + b[0]) / 2).toFixed(1)} ${((a[1] + b[1]) / 2).toFixed(1)}`;
  let d = `M${mid(p[p.length - 1], p[0])}`;
  for (let i = 0; i < p.length; i++) d += `Q${p[i][0]} ${p[i][1]} ${mid(p[i], p[(i + 1) % p.length])}`;
  return `${d}Z`;
}

